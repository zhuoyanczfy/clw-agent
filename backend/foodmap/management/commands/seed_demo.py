class Command(BaseCommand):
    help = '播种南京 11 区与示例餐厅/用餐记录'

    def add_arguments(self, parser):
        parser.add_argument('--flush', action='store_true', help='先清空餐厅与用餐记录再播种')

    def handle(self, *args, **options):
        if options['flush']:
            DiningRecord.objects.all().delete()
            Restaurant.objects.all().delete()
            self.stdout.write('已清空现有餐厅与用餐记录')

        districts = {name: District.objects.get_or_create(name=name, adcode=adcode)[0]
                     for name, adcode in DISTRICTS}

        created_restaurants = 0
        created_records = 0
        for dname, items in DEMO_DATA.items():
            for rname, address, lat, lng, records in items:
                restaurant, is_new = Restaurant.objects.get_or_create(
                    name=rname, district=districts[dname],
                    defaults={'address': address, 'lat': lat, 'lng': lng},
                )
                if is_new:
                    created_restaurants += 1
                for rdate, rating, comment, per_capita, mood in records:
                    _, rec_new = DiningRecord.objects.get_or_create(
                        restaurant=restaurant, date=rdate,
                        defaults={'rating': rating, 'comment': comment,
                                  'per_capita': per_capita, 'mood': mood},
                    )
                    if rec_new:
                        created_records += 1

        self.stdout.write(self.style.SUCCESS(
            f'播种完成：{len(DISTRICTS)} 个区，新增 {created_restaurants} 家餐厅，'
            f'{created_records} 条用餐记录'
        ))
